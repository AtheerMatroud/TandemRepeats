"""Asymmetric ancestor-descendant alignment (TCBB paper, Section 3).

Given an ancestral TR map A = a_1 ... a_n and a descendant TR map
D = d_1 ... d_m, find an optimal global alignment of D against a substring
of a string generated by a walk in the graph G_A (forward edges v_j -> v_{j+1}
free, backward edges v_k -> v_j with k >= j costing delta_{k-j}), scored by
sigma plus the duplication costs.

Initialisation follows the paper (not the JavaScript implementation):
    M[i][0] = -inf for all i,   M[0][j] = 0 and Omega[0][j] = 0 for j >= 1,
so the descendant may start against any a_j.

Each row i is filled in two rounds:
  round one   M[i][j] = max( M[i-1][j-1] + sigma(a_j, d_i),
                             M[i-1][j]   + sigma(d_i, -),
                             M[i][j-1]   + sigma(-, a_j),
                             Omega[i-1][j] + sigma(a_j, d_i) )
              Omega[i][j] = max_{j <= k <= n} M[i][k] + delta_{k-j}
  round two   M[i][j] = max( M[i][j],
                             M[i][j-1] + sigma(-, a_j),
                             Omega[i][j] + sigma(-, a_j) )

Traceback starts at the largest entry of the last row of M. The argmax k
realising each Omega[i][j] is stored, so a duplication step jumps to the
correct column, and the "gap after duplication" case of round two keeps the
descendant index fixed (this is the bookkeeping the JavaScript got wrong).

Events are reported in walk order with indices relative to the ancestor A
(1-based), in the notation of Table 4 of the paper:
    R j-k : backward edge v_k -> v_j, a duplication of a_j ... a_k
    S j   : mismatch against a_j (variant substitution)
    D j   : a_j aligned against a gap (deletion of a_j)
    I i   : d_i aligned against a gap (insertion, not in the paper's tables)
The distance estimate is Equation (3.1):
    d_est = -( score - sum of match rewards on the alignment ).
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import List, Optional, Sequence, Tuple

from .scoring import GAP, Scoring, delta_vector

NEG_INF = float("-inf")


@dataclass(frozen=True)
class Event:
    kind: str            # 'R', 'S', 'D', 'I', or 'M' (match; omitted from summaries)
    start: int           # ancestor index (1-based); for 'I', ancestor index reached so far
    end: Optional[int] = None   # for 'R': the k of the backward edge v_k -> v_j
    desc: Optional[int] = None  # descendant index (1-based) involved, if any

    def __str__(self) -> str:
        if self.kind == "R":
            return f"R{self.start}" if self.end == self.start else f"R{self.start}-{self.end}"
        if self.kind == "I":
            return f"I{self.desc}"
        return f"{self.kind}{self.start}"


@dataclass
class Alignment:
    ancestor: List[str]
    descendant: List[str]
    score: float
    distance: float                 # Equation (3.1)
    walk: List[int]                 # ancestor indices visited (1-based), in order
    aligned_walk: List[str]         # W-bar, with '-' for gaps
    aligned_descendant: List[str]   # D-bar, with '-' for gaps
    events: List[Event]             # in walk order, matches included as kind 'M'
    start_index: int                # ancestor index where the alignment starts
    end_index: int                  # ancestor index where the alignment ends
    M: Optional[List[List[float]]] = field(default=None, repr=False)

    def event_summary(self, include_matches: bool = False) -> List[Event]:
        return [e for e in self.events if include_matches or e.kind != "M"]

    def event_string(self) -> str:
        """Events in Table 4 style; runs of consecutive deletions are merged (D20-21)."""
        out: List[str] = []
        run_start = run_end = None
        for e in self.event_summary():
            if e.kind == "D":
                if run_start is not None and e.start == run_end + 1:
                    run_end = e.start
                else:
                    if run_start is not None:
                        out.append(_drange(run_start, run_end))
                    run_start = run_end = e.start
                continue
            if run_start is not None:
                out.append(_drange(run_start, run_end))
                run_start = run_end = None
            out.append(str(e))
        if run_start is not None:
            out.append(_drange(run_start, run_end))
        return " ".join(out)

    def pretty(self) -> str:
        top = " ".join(self.aligned_walk)
        mid = " ".join("|" if a == d else ("*" if a != GAP and d != GAP else " ")
                       for a, d in zip(self.aligned_walk, self.aligned_descendant))
        bot = " ".join(self.aligned_descendant)
        return f"{top}\n{mid}\n{bot}"


def _drange(s: int, e: int) -> str:
    return f"D{s}" if s == e else f"D{s}-{e}"


def parse_event_string(text: str) -> List[Event]:
    """Parse Table 4 notation ("R7-8 S8 D20-21 D48") into Events (D ranges expanded)."""
    out: List[Event] = []
    for tok in text.split():
        kind, body = tok[0], tok[1:]
        if "-" in body:
            s, e = (int(x) for x in body.split("-"))
        else:
            s = e = int(body)
        if kind == "R":
            out.append(Event("R", s, e))
        elif kind == "D":
            out.extend(Event("D", j) for j in range(s, e + 1))
        elif kind == "S":
            out.append(Event("S", s))
        else:
            raise ValueError(f"cannot parse event token {tok!r}")
    return out


def replay_events(
    A: Sequence[str],
    events: Sequence[Event] | str,
    D: Optional[Sequence[str]] = None,
    scoring: Optional[Scoring] = None,
    delta: Optional[Sequence[float]] = None,
    d: float = -10.0,
    eps: float = -1.0,
    start: int = 1,
) -> Tuple[List[str], float]:
    """Apply an event list in walk order to A and return (result, cost).

    R j-k: emit a_p..a_k then jump back to j;  S j: emit the descendant's symbol
    at that step ('?' if D is not given);  D j: skip a_j. Remaining symbols to a_n
    are emitted at the end. The cost is the paper's edit weight: -delta for each
    duplication, -sigma for each substitution (needs D and scoring), -gap for
    each deletion. Used to check that two event lists are indistinguishable.
    """
    A = list(A)
    n = len(A)
    if isinstance(events, str):
        events = parse_event_string(events)
    if delta is None:
        delta = delta_vector(n, d, eps)
    out: List[str] = []
    cost = 0.0
    p = start

    def emit_through(q: int) -> None:
        nonlocal p
        while p <= q:
            out.append(A[p - 1]); p += 1

    for e in events:
        if e.kind == "R":
            emit_through(e.end)
            cost += -delta[e.end - e.start]
            p = e.start
        elif e.kind == "S":
            emit_through(e.start - 1)
            sym = "?"
            if D is not None and len(out) < len(D):
                sym = D[len(out)]
            if scoring is not None and sym != "?":
                cost += -scoring.sigma(A[e.start - 1], sym)
            out.append(sym); p = e.start + 1
        elif e.kind == "D":
            emit_through(e.start - 1)
            if scoring is not None:
                cost += -scoring.sigma(A[e.start - 1], GAP)
            p = e.start + 1
        elif e.kind == "M":
            emit_through(e.start)
        elif e.kind == "I":
            emit_through(e.start)
            out.append("?")
    emit_through(n)
    return out, cost


def align(
    A: Sequence[str],
    D: Sequence[str],
    scoring: Scoring,
    delta: Optional[Sequence[float]] = None,
    d: float = -10.0,
    eps: float = -1.0,
    keep_matrix: bool = False,
    anchored: bool = False,
) -> Alignment:
    """Align descendant D against walks in G_A (paper Section 3.2). Returns an Alignment.

    anchored=False (paper): D is aligned against a substring of a walk, so the
        walk may start at any a_j and stop anywhere; unmatched copies at the two
        ends of A cost nothing (M[0][j] = 0, traceback from the best last-row entry).
    anchored=True: the walk must start at a_1 and end at a_n; leading and
        trailing copies of A not present in D are charged as deletions.
    """
    A = list(A)
    D = list(D)
    n, m = len(A), len(D)
    if n == 0:
        raise ValueError("ancestor must be non-empty")
    if delta is None:
        delta = delta_vector(n, d, eps)
    if len(delta) < n:
        raise ValueError("delta must have at least len(A) entries")
    sig = scoring.sigma

    # Precompute gap costs per column and per row.
    # Scoring.sigma takes (ancestor symbol, descendant symbol); the paper writes sigma(d_i, a_j).
    gapA = [0.0] + [sig(A[j - 1], GAP) for j in range(1, n + 1)]   # a_j against gap (ancestor-side gap)
    gapD = [0.0] + [sig(GAP, D[i - 1]) for i in range(1, m + 1)]   # d_i against gap (descendant-side gap)

    M = [[NEG_INF] * (n + 1) for _ in range(m + 1)]
    Om = [[NEG_INF] * (n + 1) for _ in range(m + 1)]
    Oarg = [[0] * (n + 1) for _ in range(m + 1)]
    # ptr[i][j] = (kind, i', j') : kind in diag, up, left, dup, dupgap
    ptr: List[List[Optional[Tuple[str, int, int]]]] = [[None] * (n + 1) for _ in range(m + 1)]

    if anchored:
        M[0][0] = 0.0
        for j in range(1, n + 1):
            M[0][j] = M[0][j - 1] + gapA[j]
            ptr[0][j] = ("left", 0, j - 1)
            Om[0][j] = NEG_INF
            Oarg[0][j] = j
    else:
        for j in range(1, n + 1):
            M[0][j] = 0.0
            Om[0][j] = 0.0
            Oarg[0][j] = j

    # ---- dynamic programme (NumPy per row; pointers kept as compact integer codes) ----
    # Row-wise vectorisation: round one is a left-to-right scan (the "left" term is
    # sequential), Omega is an O(n^2) max over k >= j done with a matrix, round two is
    # a sequential scan. Pointer codes: 0 diag, 1 dup, 2 up, 3 left, 4 dupgap.
    import numpy as np
    symsA = A; symsD = D
    # sigma table: rows descendant symbols, columns ancestor symbols (unique symbols only)
    uA = sorted(set(A)); uD = sorted(set(D))
    ia = {x: k for k, x in enumerate(uA)}; idd = {x: k for k, x in enumerate(uD)}
    S = np.array([[sig(a, dd) for a in uA] for dd in uD], dtype=float)
    colA = np.array([ia[a] for a in A]); rowD = [idd[dd] for dd in D]
    gA = np.array(gapA, dtype=float); gD = gapD
    dl = np.array(delta[:n], dtype=float)
    # delta matrix: DL[j, k] = delta[k - j] for k >= j else -inf (1-based j, k -> 0-based)
    jj, kk = np.meshgrid(np.arange(n), np.arange(n), indexing="ij")
    DL = np.where(kk >= jj, dl[np.clip(kk - jj, 0, n - 1)], NEG_INF)

    Mprev = np.array(M[0], dtype=float)            # length n+1
    Oprev = np.array(Om[0], dtype=float)
    Oargprev = list(Oarg[0])
    kinds = np.empty((m + 1, n + 1), dtype=np.int8)
    oarg_rows = [Oargprev]
    for i in range(1, m + 1):
        srow = S[rowD[i - 1]][colA]                # sigma(a_j, d_i) for j = 1..n (0-based j-1)
        diag = Mprev[:-1] + srow
        dup = Oprev[1:] + srow
        up = Mprev[1:] + gD[i]
        Mcur = np.empty(n + 1); Mcur[0] = NEG_INF
        kind = np.where(diag >= dup, 0, 1)
        best = np.maximum(diag, dup)
        kind = np.where(up > best, 2, kind); best = np.maximum(best, up)
        # sequential left term
        Mrow = best.copy()
        krow = kind.copy()
        prev = Mcur[0]
        for j in range(n):
            left = prev + gA[j + 1]
            if left > Mrow[j]:
                Mrow[j] = left; krow[j] = 3
            prev = Mrow[j]
        Mcur[1:] = Mrow
        # Omega from round-one values
        cand = Mrow[None, :] + DL                  # [j, k]
        Oarg_cur = np.argmax(cand, axis=1)         # 0-based k
        Ocur = np.empty(n + 1); Ocur[0] = NEG_INF; Ocur[1:] = cand[np.arange(n), Oarg_cur]
        Oargc = [0] + [int(k) + 1 for k in Oarg_cur]
        # round two (sequential)
        prev = Mcur[0]
        for j in range(1, n + 1):
            left = prev + gA[j]
            dupgap = Ocur[j] + gA[j]
            if left > Mcur[j] and left >= dupgap:
                Mcur[j] = left; krow[j - 1] = 3
            elif dupgap > Mcur[j]:
                Mcur[j] = dupgap; krow[j - 1] = 4
            prev = Mcur[j]
        kinds[i, 1:] = krow
        M[i] = Mcur.tolist()
        Mprev, Oprev, Oargprev = Mcur, Ocur, Oargc
        oarg_rows.append(Oargc)

    def ptr_at(i: int, j: int):
        if i == 0:
            return ptr[0][j]
        k = int(kinds[i, j])
        if k == 0: return ("diag", i - 1, j - 1)
        if k == 1: return ("dup", i - 1, oarg_rows[i - 1][j])
        if k == 2: return ("up", i - 1, j)
        if k == 3: return ("left", i, j - 1)
        return ("dupgap", i, oarg_rows[i][j])

    # traceback from the largest entry of the last row (prefer the right-most on ties,
    # so the walk ends at a_n whenever an optimal alignment does)
    jbest = n if anchored else max(range(1, n + 1), key=lambda j: (M[m][j], j))
    score = M[m][jbest]

    steps: List[Tuple[str, int, int]] = []   # (kind, i, j) of the cell being left
    i, j = m, jbest
    while i > 0 or (anchored and j > 0):
        kind, ni, nj = ptr_at(i, j)
        steps.append((kind, i, j))
        i, j = ni, nj
    steps.reverse()

    events: List[Event] = []
    walk: List[int] = []
    wbar: List[str] = []
    dbar: List[str] = []
    match_total = 0.0

    def visit(jj: int, ii: Optional[int]) -> None:
        """Arrive at a_jj; ii is the descendant index matched, or None for a gap."""
        walk.append(jj)
        if ii is None:
            wbar.append(A[jj - 1]); dbar.append(GAP)
            events.append(Event("D", jj))
        else:
            wbar.append(A[jj - 1]); dbar.append(D[ii - 1])
            if A[jj - 1] == D[ii - 1]:
                events.append(Event("M", jj, desc=ii))
            else:
                events.append(Event("S", jj, desc=ii))

    for kind, ci, cj in steps:
        if kind == "diag":
            visit(cj, ci)
        elif kind == "up":
            wbar.append(GAP); dbar.append(D[ci - 1])
            events.append(Event("I", cj, desc=ci))
        elif kind == "left":
            visit(cj, None)
        elif kind == "dup":
            k = ptr_at(ci, cj)[2]
            # A "duplication" whose source is row 0 is the free start (Omega[0][j] = 0), not an event.
            if ci - 1 > 0:
                events.append(Event("R", cj, k))
            visit(cj, ci)
        elif kind == "dupgap":
            k = ptr_at(ci, cj)[2]
            events.append(Event("R", cj, k))
            visit(cj, None)

    for a, dd in zip(wbar, dbar):
        if a != GAP and a == dd:
            match_total += sig(a, dd)
    distance = -(score - match_total)
    start_index = walk[0] if walk else jbest

    return Alignment(
        ancestor=A, descendant=D, score=score, distance=distance,
        walk=walk, aligned_walk=wbar, aligned_descendant=dbar, events=events,
        start_index=start_index, end_index=jbest,
        M=M if keep_matrix else None,
    )
